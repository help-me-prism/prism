import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import { transformWithOxc } from 'vite'
const shared=await transformWithOxc(await fs.readFile('electron/scientificSource.ts','utf8'),'electron/scientificSource.ts')
const sharedUrl='data:text/javascript;base64,'+Buffer.from(shared.code).toString('base64')
const harnessSource=(await fs.readFile('electron/translationHarness.ts','utf8')).replaceAll("'./scientificSource.js'",JSON.stringify(sharedUrl))
const {code}=await transformWithOxc(harnessSource,'electron/translationHarness.ts')
const {prepareTranslationRequest,inspectTranslationRequest,inspectTranslationBatch,translationBatches,translationPromptCharacterLimit}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'))
const largeItems = Array.from({length: 20}, (_, i) => ({id: `large-${i}`, source: 'measurement 1.25 mg '.repeat(200), paragraphContext: 'context '.repeat(500), blockId: `block-${i}`}))
const budgeted = translationBatches(largeItems, () => 'adjacent '.repeat(300))
assert.deepEqual(budgeted.flat().map(x => x.id), largeItems.map(x => x.id))
assert(budgeted.every(batch => prepareTranslationRequest(batch, 'adjacent '.repeat(300)).prompt.length <= translationPromptCharacterLimit))
assert.throws(() => translationBatches([{id: 'oversized', source: 'x'.repeat(30_000)}], () => ''), /너무 큽니다/)
const fixture=JSON.parse(await fs.readFile('scripts/fixtures/engineering-p11-malformed-translation.json','utf8'))
assert.throws(()=>inspectTranslationBatch(fixture.output,fixture.input),/ID/,'Actual corrupted s15 hash must never be guessed or remapped')
const request=prepareTranslationRequest(fixture.input)
assert.deepEqual(request.items.map(i=>i.id),Array.from({length:16},(_,i)=>`t${i}`))
assert(request.prompt.includes('"id":"t0"'))
assert(!request.prompt.includes('p11-s15-p3qndn'),'Long cache anchors must not enter the model copy task')
const reply=request.modelItems.map(i=>({id:i.id,translation:"검증 번역: "+i.source})).reverse()
const checked=inspectTranslationRequest(JSON.stringify(reply),request)
assert.equal(checked.accepted.size,16)
assert.equal(checked.accepted.get(fixture.input[14].id),'검증 번역: '+fixture.input[14].source,'Response order must not affect exact reverse mapping')
const missing=inspectTranslationRequest(JSON.stringify(reply.slice(1)),request)
assert.equal(missing.accepted.size,15)
assert.deepEqual(missing.rejected.map(r=>r.id),[fixture.input[15].id])
assert.throws(()=>inspectTranslationRequest(JSON.stringify([...reply,{...reply[0]}]),request),/ID/)
assert.throws(()=>inspectTranslationRequest(JSON.stringify([{id:'t16',translation:'unknown'}]),request),/ID/)
assert.throws(()=>inspectTranslationRequest(JSON.stringify([{id:fixture.input[0].id,translation:'wrong namespace'}]),request),/ID/)
assert.throws(()=>prepareTranslationRequest([fixture.input[0],fixture.input[0]]),/중복/)
const repeated=prepareTranslationRequest([{id:'a',source:'Same.'},{id:'b',source:'Same.'}])
assert.equal(inspectTranslationRequest('[{"id":"t1","translation":"두 번째"},{"id":"t0","translation":"첫 번째"}]',repeated).accepted.get('a'),'첫 번째')
console.log('Translation request passed: short exact identities, ordered-independent mapping, missing salvage, strict duplicate/unknown rejection, real Luna corruption remains rejected.')

