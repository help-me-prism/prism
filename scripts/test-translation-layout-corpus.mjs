import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import { loadTs as load } from './load-ts.mjs'

const { segmentsFromItems, hasDamagedMathEncoding } = await load('src/paper/textExtraction.ts')
const { preservePdfTables } = await load('src/paper/tableRegions.ts')
const { preservePublicationFurniture } = await load('src/paper/publicationFurniture.ts')
const { withoutBibliography } = await load('electron/translationScope.ts')
const fixtures = JSON.parse(await fs.readFile('scripts/fixtures/translation-layout-corpus.json', 'utf8'))
const extract = (paper, page) => {
 const f = fixtures.find(f => f.paper === paper && f.page === page)
 return segmentsFromItems(page, f.items).map(s => ({ ...s, preciseRects: s.itemIndexes.map(index => {const i = f.items[index]; return {left:i.transform[4],top:f.height-i.transform[5]-i.height,width:i.width,height:i.height,fontSize:i.height}}) }))
}
const algorithm = extract('2606.02682', 9)
assert.equal(algorithm.find(s=>s.source.startsWith('Algorithm 2')).kind,'table')
assert(algorithm.some(s=>s.kind==='text'&&s.source.startsWith('The input to the model')))
const references = extract('2609.00689', 6)
assert.equal(references.find(s=>s.source==='References').kind,'heading')
assert(!withoutBibliography(references).some(s=>s.source.startsWith('Yuwei')))
const appendix = extract('2609.00689', 8)
assert(appendix.some(s=>s.kind==='heading'&&s.source==='A.1 Neuron Mining Dataset Setting'))
assert(appendix.some(s=>s.kind==='text'&&s.source.startsWith('For neuron mining')))
const prompts = preservePdfTables(appendix)
assert(prompts.filter(s=>/^(System:|User:|Question:|Document N:)/.test(s.source)).every(s=>s.kind==='table'))
assert(withoutBibliography([...references,...appendix]).some(s=>s.source.startsWith('For neuron mining')))
const fsdr = preservePdfTables(extract('2103.02370',3))
assert(fsdr.filter(s=>/^(Band-reject|Target acc\.|Null \(with)/.test(s.source)).every(s=>s.kind==='table'))
assert(fsdr.some(s=>s.kind==='text'&&s.source.startsWith('reject filter')))
const neighboring = preservePdfTables(extract('2609.00689',9))
const random = neighboring.find(s=>s.source.startsWith('Random (seed 42)'))
const caption = neighboring.find(s=>s.source.startsWith('Table 9:'))
assert.equal(random.blockId,'pdf-table-'+caption.id,'A bigger following table cannot steal the nearer caption')
const crispr = preservePublicationFurniture(extract('doi_10.1126_science.1225829',2),new Map([[2,{width:612,height:792}]]))
assert(crispr.filter(s=>s.source.includes('HHMI Author Manuscript')||s.source.includes('Author manuscript;')).every(s=>s.kind==='artifact'))
const ligo = extract('1602.03837',9)
assert(!withoutBibliography(ligo).some(s=>/^\[1\]/.test(s.source)), 'Untitled consecutive bibliography is excluded')
assert(withoutBibliography(ligo).some(s=>s.source.includes('document numbers')), 'The preceding acknowledgment remains prose')
const lecture = extract('local-de4732581831050ab719effc',2)
assert(lecture.filter(s=>s.source.startsWith('•')).length>=8,'Slide bullets keep separate reading blocks')
const positioned = (str,y) => ({str,width:200,height:10,transform:[10,0,0,10,100,y],hasEOL:true})
const abbreviation = segmentsFromItems(1,[positioned('Prof. Smith used 0 . 5 mg in Fig. 2. The result was stable.',700)])
assert.equal(abbreviation.length,2)
assert(abbreviation[0].source.includes('0 . 5 mg'))
console.log('Real corpus passed: algorithms, PDF-only tables, prompt cells, adjacent tables, references, appendix boundaries, manuscript furniture, slide bullets and abbreviation offsets.')
const doubleCaption = preservePdfTables(extract('2103.02370',8))
assert.equal(doubleCaption.find(s=>s.source==='w/ Tgt').blockId,'pdf-table-'+doubleCaption.find(s=>s.source.startsWith('Table 5.')).id,'A following caption cannot reclaim an already assigned table')
const stacked = preservePdfTables(extract('2609.00689',11))
assert.equal(stacked.find(s=>s.source.startsWith('# Samples')).blockId,'pdf-table-'+stacked.find(s=>s.source.startsWith('Table 13:')).id,'A numeric table above its caption is not displaced by headers of the next table')
const romanTable = preservePdfTables(extract('1602.03837',7))
assert(romanTable.find(s=>s.kind==='caption'&&s.source.startsWith('TABLE I.')).source.includes('results of different waveform models.'),'An inline word results must not start a section')
assert.equal(romanTable.find(s=>s.source.startsWith('Primary black hole mass')).kind,'table','The first cell of a Roman-numbered table is preserved with its asymmetric error bars')

assert(hasDamagedMathEncoding('To convert multiply by ( 1 þ z ) [90].'),'Do not translate an already corrupt plus sign in a caption')
assert(!hasDamagedMathEncoding('The Icelandic author Þór used a quarter (¼) of the sample.'))
