import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import {transformWithOxc} from 'vite'
const {code}=await transformWithOxc(await fs.readFile('src/contextRequestGate.ts','utf8'),'src/contextRequestGate.ts')
const {createContextRequestGate,noteContextSignature}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'))
const node=(id,revision='r1')=>({id,revision,title:id,nodeType:'concept',relativePath:`Concepts/${id}.md`})
const inventory=[node('active'),node('other')]
assert.equal(noteContextSignature(inventory),noteContextSignature([...inventory].reverse().map(n=>({...n,modifiedAt:100}))), 'Equivalent fresh arrays/reordering/mtime must not change context')
assert.notEqual(noteContextSignature(inventory),noteContextSignature([node('active'),node('other','edited')]), 'Other-note content changes must refresh backlinks even at the same count')
assert.notEqual(noteContextSignature(inventory),noteContextSignature([node('active'),{...node('other'),title:'Renamed'}]))
assert.notEqual(noteContextSignature(inventory),noteContextSignature([node('active'),node('replacement')]))
const gate=createContextRequestGate()
const a={vault:'one',id:'a',nodes:[]};gate.setOwner(a)
const first=gate.begin(a),second=gate.begin(a)
assert(!first());assert(second(),'Latest overlapping request owns results and loading/errors')
gate.setOwner({vault:'one',id:'b',nodes:[]})
gate.setOwner(a)
assert(!second(),'A→B→A cannot resurrect an earlier response even with the identical owner object')
const third=gate.begin(a)
gate.setOwner({vault:'two',id:'a',nodes:[]})
assert(!third(),'Same note ID in a different vault is a different context')
const current={vault:'two',id:'a',nodes:[{id:'a'}]};gate.setOwner(current)
const beforeExternalEdit=gate.begin(current)
gate.setOwner({...current,nodes:[{id:'a',title:'external edit'}]})
assert(!beforeExternalEdit(),'Same-count node refresh invalidates old context')
gate.setOwner(current)
const pending=gate.begin(current);gate.invalidate()
assert(!pending(),'Unmount or immediate vault-change invalidation suppresses stale writes')
console.log('context-request-gate: overlap, ABA, vault identity, same-count refresh and invalidation passed')
